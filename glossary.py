"""
glossary.py
------------------------------------------------------------
グラフや株式投資でよく出てくる「用語」の解説をまとめたファイルです。
要件定義書 7.4節(学習支援機能)・7.7節(用語検索機能)に対応します。

このファイルには、用語とその説明の一覧(データ)と、検索の処理だけを
置いています。画面への表示や、検索結果を見やすく装飾する処理は
main.py 側で行います(役割分担:データはここ、見せ方はmain.py)。
"""

# ---- 用語集 ----
# 要件定義書 第4章の表(初心者向け早見表)に、7.4節で触れている
# チャート用語(始値・終値・高値・安値・出来高)を加えたものです。
# 1件は (用語, 説明) のタプル。表示順もこの並び順を使います。
GLOSSARY = [
    ("証券コード", "日本株を識別する4桁の番号(例:トヨタ自動車=7203)。"),
    ("ティッカーシンボル", "米国株などを識別するアルファベットの略称(例:Apple=AAPL)。"),
    ("始値(はじめね)", "その日(または期間)の取引で、最初についた価格。"),
    ("終値(おわりね)", "その日(または期間)の取引で、最後についた価格。本ツールのグラフは基本的にこの値を使う。"),
    ("高値(たかね)", "その日(または期間)の取引で、一番高かった価格。"),
    ("安値(やすね)", "その日(または期間)の取引で、一番安かった価格。"),
    ("出来高(できだか)", "その日(または期間)に、実際にどれだけの株数が売買されたかを示す数値。多いほど、その日の値動きに多くの投資家が反応したことを意味する。"),
    ("前日比", "前の営業日の終値と比べて、いくら(円・ptなど)変わったか。「1: ウォッチリストを表示する」でも確認できる。"),
    ("騰落率(とうらくりつ)", "前日比などを%(パーセント)で表したもの。本ツールの「変化率」表示も同じ考え方。"),
    ("時価総額", "株価 × 発行済み株式数。その会社の市場での大きさの目安(本ツールでは扱っていません)。"),
    ("配当", "会社が利益の一部を株主に還元するお金(本ツールでは扱っていません)。"),
    ("営業日", "証券取引所が開いている日。土日・祝日は休みで、株価は動かない。"),
    ("指数(しすう)", "個別の会社ではなく、多くの銘柄をまとめて動きを表す数値(例:日経平均株価、NASDAQ総合指数)。"),
    ("決算", "会社が一定期間の売上や利益をまとめて発表すること。株価が動く代表的なきっかけの一つ。"),
    ("移動平均線", "直近の一定期間の終値を平均した値をつないだ線。日々の細かい上下動に惑わされず、大まかな流れをつかむために使う(フェーズ6で実装予定)。"),
    ("ボリンジャーバンド", "移動平均線の上下に、値動きのばらつきの幅を示した帯状の線。買われすぎ・売られすぎの目安として使われる(将来機能)。"),
    ("テクニカル分析", "過去の値動きや出来高などの指標から、今後の値動きの傾向を読もうとする分析方法(将来機能)。"),
    ("予測ライン", "テクニカル指標から算出する、今後の値動きの参考予測線。将来の値動きを保証するものではない(フェーズ7で検討予定)。"),
    ("売買シグナル", "予測ラインなどをもとにした、買い時・売り時の目安を示す補助的な表示(フェーズ7で検討予定)。"),
]


def search_glossary(keyword):
    """
    キーワードで用語集を検索する関数。
    「用語の名前」と「説明文」の両方から、大文字・小文字を区別せず
    部分一致で検索する(例: "利益" で検索すると、説明文に「利益」を
    含む「決算」なども見つかる)。

    戻り値は、一致した (用語, 説明) のリスト。1件も一致しなければ空リスト。
    """
    keyword_clean = keyword.strip().lower()
    if keyword_clean == "":
        return []

    results = []
    for term, description in GLOSSARY:
        if keyword_clean in term.lower() or keyword_clean in description.lower():
            results.append((term, description))
    return results
